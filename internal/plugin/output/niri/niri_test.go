// TestMain pins HOME (which the template loader's override base derives from)
// and XDG_CONFIG_HOME to a temp dir so tests render the embedded templates
// rather than any user overrides in ~/.config/tinct/templates.
func TestMain(m *testing.M) {
	dir, err := os.MkdirTemp("", "tinct-niri-test-home")
	if err != nil {
		panic(err)
	}
	os.Setenv("HOME", dir)
	os.Setenv("XDG_CONFIG_HOME", filepath.Join(dir, ".config"))
	code := m.Run()
	_ = os.RemoveAll(dir)
	os.Exit(code)
}

// TestNiriPlugin runs all standard plugin tests using shared utilities.
func TestNiriPlugin(t *testing.T) {
	plugin := New()

	t.Run("Name", func(t *testing.T) {
		if plugin.Name() != "niri" {
			t.Errorf("Name() = %s, want niri", plugin.Name())
		}
	})

	t.Run("Description", func(t *testing.T) {
		if plugin.Description() == "" {
			t.Error("Description() should not be empty")
		}
	})

	t.Run("DefaultOutputDir", func(t *testing.T) {
		dir := plugin.DefaultOutputDir()
		if dir == "" {
			t.Error("DefaultOutputDir() should not be empty")
		}
		if !strings.Contains(dir, "niri") {
			t.Errorf("DefaultOutputDir() = %s, should contain 'niri'", dir)
		}
	})

	expectedFiles := []string{"tinct-colours.kdl", "tinct.kdl"}

	plugintesting.TestGeneration(t, plugin, expectedFiles)
	plugintesting.TestPreExecuteHook(t, plugin, "niri")
	plugintesting.TestFlags(t, plugin, "niri")
}

// TestNiriPlugin_ContentValidation tests niri-specific content requirements.
func TestNiriPlugin_ContentValidation(t *testing.T) {
	palette := plugintesting.CreateTestPalette(colour.ThemeDark)
	plugin := New()

	themeData := colour.NewThemeData(palette, "", "", "")
	files, err := plugin.Generate(themeData)
	if err != nil {
		t.Fatalf("Generate() error = %v", err)
	}

	content := string(files["tinct-colours.kdl"])

	requiredStrings := []string{
		"niri colour theme generated by Tinct",
		"focus-ring",
		"active-gradient",
		"tab-indicator",
		"overview",
		"backdrop-color",
		"Detected theme: dark",
	}
	for _, required := range requiredStrings {
		if !strings.Contains(content, required) {
			t.Errorf("Generated content missing required string: %s", required)
		}
	}

	// Colours must render as #rrggbb hex strings, not empty templates.
	if !strings.Contains(content, "active-color \"#") {
		t.Error("Generated content missing hex colour values")
	}
	if strings.Contains(content, "\"#\"") {
		t.Error("Generated content contains empty hex colour - templating failed")
	}
}

