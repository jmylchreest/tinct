// TestNiriPlugin_GenerateWithStub tests stub file generation with a custom path.
func TestNiriPlugin_GenerateWithStub(t *testing.T) {
	palette := plugintesting.CreateTestPalette(colour.ThemeDark)
	plugin := New()
	plugin.generateStub = true
	plugin.stubPath = "custom-niri.kdl"

	themeData := colour.NewThemeData(palette, "", "", "")
	files, err := plugin.Generate(themeData)
	if err != nil {
		t.Fatalf("Generate() error = %v", err)
	}

	if len(files) != 2 {
		t.Fatalf("Generate() with stub returned %d files, want 2", len(files))
	}
	if _, ok := files["tinct-colours.kdl"]; !ok {
		t.Error("Generate() did not return tinct-colours.kdl")
	}

	stubFile := filepath.Base(plugin.stubPath)
	stub, ok := files[stubFile]
	if !ok {
		t.Fatalf("Generate() did not return stub file %s", stubFile)
	}
	if !strings.Contains(string(stub), "include") {
		t.Error("Stub file should document the include directive")
	}
}

