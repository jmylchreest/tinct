// TestNiriPlugin_GetEmbeddedTemplates tests embedded template access.
func TestNiriPlugin_GetEmbeddedTemplates(t *testing.T) {
	fs := GetEmbeddedTemplates()

	entries, err := fs.ReadDir(".")
	if err != nil {
		t.Fatalf("ReadDir() error = %v", err)
	}

	foundColours := false
	foundStub := false
	for _, entry := range entries {
		switch entry.Name() {
		case "tinct-colours.kdl.tmpl":
			foundColours = true
		case "tinct.kdl.tmpl":
			foundStub = true
		}
	}

	if !foundColours {
		t.Error("Template tinct-colours.kdl.tmpl not found in embedded filesystem")
	}
	if !foundStub {
		t.Error("Template tinct.kdl.tmpl not found in embedded filesystem")
	}
}
